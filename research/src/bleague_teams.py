def normalize_team(raw_name):
    raw = raw_name.strip()
    # Strip suffixes like (1位), （レギュラー・2位）, etc.
    import re
    cleaned = re.sub(r'[\(（].*?[\)）]', '', raw).strip()
    
    if cleaned in TEAM_MAPPINGS:
        return TEAM_MAPPINGS[cleaned]
    if raw in TEAM_MAPPINGS:
        return TEAM_MAPPINGS[raw]
        
    for k in sorted(TEAM_MAPPINGS.keys(), key=len, reverse=True):
        if k in raw:
            return TEAM_MAPPINGS[k]
            
    # Fallback
    return {
        "en": cleaned if cleaned else raw,
        "ja": raw,
        "full_en": cleaned if cleaned else raw,
        "city": "Japan",
        "prefecture": "Japan",
        "arena_en": "Arena",
        "arena_ja": "体育館",
    }
