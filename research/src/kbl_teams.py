def translate_team(name):
    if not name:
        return ""
    name_clean = name.strip()
    if name_clean in TEAM_NAME_MAP:
        return TEAM_NAME_MAP[name_clean]
    for k, v in TEAM_NAME_MAP.items():
        if k in name_clean:
            return v
    return name_clean

def translate_venue(name):
    if not name:
        return ("Unknown Venue", "South Korea")
    name_clean = name.strip()
    if name_clean in STADIUM_MAP:
        return STADIUM_MAP[name_clean]
    for k, v in STADIUM_MAP.items():
        if k in name_clean:
            return v
    return (name_clean, "South Korea")
