TEAMS = {"Aces": 1.35, "Bats": 1.15, "Cards": 1.0, "Docks": 1.0, "Eels": 0.85, "Fins": 0.7}
VENUES = {"Aces": 11, "Bats": 12, "Cards": 13, "Docks": 14, "Eels": 15, "Fins": 16}
PARK = {11: 1.0, 12: 1.0, 13: 1.0, 14: 1.3, 15: 1.0, 16: 1.0}


def synth_schedule(n_days=90, seed=3):
    """A season where team strength and one hitter-friendly park are real, generated by a shared-gamma
    Poisson process so the model family is correct."""
    rng = random.Random(seed)
    names = list(TEAMS)
    dates, pk = [], 700000
    start = dt.date(2026, 4, 1)
    for i in range(n_days):
        d = (start + dt.timedelta(days=i)).isoformat()
        order = names[:]
        rng.shuffle(order)
        games = []
        for h, a in zip(order[0::2], order[1::2]):
            z = rng.gammavariate(7.0, 1 / 7.0)
            base = 4.45 * PARK[VENUES[h]] * z
            lam_h = base * TEAMS[h] / TEAMS[a] * 1.03
            lam_a = base * TEAMS[a] / TEAMS[h] * 0.97

            def pois(lam):
                L, k, p = math.exp(-lam), 0, 1.0
                while True:
                    p *= rng.random()
                    if p <= L:
                        return k
                    k += 1
            hr, ar = pois(lam_h), pois(lam_a)
            while hr == ar:  # completed games cannot tie
                hr += rng.random() < 0.52
                ar += hr == ar
            pk += 1
            games.append({"gamePk": pk, "officialDate": d,
                          "status": {"abstractGameState": "Final", "detailedState": "Final"},
                          "venue": {"id": VENUES[h]},
                          "teams": {"home": {"team": {"name": h}, "score": hr}, "away": {"team": {"name": a}, "score": ar}}})
        dates.append({"date": d, "games": games})
    return {"dates": dates}


def feed(pk, when="2026-07-01T23:05:00Z", official="2026-07-01", state="Preview", home="Aces", away="Fins",
         hid=501, aid=502, linescore=None):
    f = {"gameData": {"datetime": {"dateTime": when, "officialDate": official}, "status": {"abstractGameState": state},
                      "teams": {"home": {"name": home}, "away": {"name": away}}, "venue": {"id": VENUES[home]},
                      "probablePitchers": {"home": {"id": hid}, "away": {"id": aid}}},
         "liveData": {}}
    if linescore:
        f["liveData"]["linescore"] = linescore
    return f


def people(ip, r, hr, bb, k, gs):
    return {"stats": [{"splits": [{"stat": {"inningsPitched": ip, "runs": r, "earnedRuns": r, "homeRuns": hr,
                                             "baseOnBalls": bb, "hitByPitch": 1, "strikeOuts": k, "gamesStarted": gs}}]}]}


